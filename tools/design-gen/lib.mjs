// ── Read ────────────────────────────────────────────────────────────────

const readJson = (rel) => JSON.parse(readFileSync(join(ROOT, rel), "utf8"));

export function loadDesign() {
  const tokens = {
    color: readJson("design/tokens/color.json"),
    typography: readJson("design/tokens/typography.json"),
    spacing: readJson("design/tokens/spacing.json"),
    sizing: readJson("design/tokens/sizing.json"),
    effects: readJson("design/tokens/effects.json"),
    layout: readJson("design/tokens/layout.json"),
  };
  const locales = ["ko", "en"];
  const strings = Object.fromEntries(locales.map((l) => [l, readJson(`design/strings/${l}.json`)]));
  return { tokens, locales, strings };
}

/** Ensure every locale has the same key set before generating; otherwise the Swift/Kotlin tables would have holes. */
function assertSameKeys({ locales, strings }) {
  const ref = Object.keys(strings[locales[0]]);
  for (const l of locales) {
    const missing = ref.filter((k) => !(k in strings[l]));
    const extra = Object.keys(strings[l]).filter((k) => !ref.includes(k));
    if (missing.length || extra.length)
      throw new Error(`design/strings/${l}.json 키 불일치 — 없음: [${missing.join(", ")}] · 남음: [${extra.join(", ")}]. pnpm design:check 로 확인`);
  }
}

// ── Names ───────────────────────────────────────────────────────────────

const parts = (name) => String(name).split(/[.\-_]/).filter(Boolean);
export const camel = (name) =>
  parts(name).map((p, i) => (i === 0 ? p[0].toLowerCase() + p.slice(1) : p[0].toUpperCase() + p.slice(1))).join("");
export const kebab = (name) =>
  parts(name).map((p) => p.replace(/([a-z0-9])([A-Z])/g, "$1-$2").toLowerCase()).join("-");
const upperSnake = (name) => kebab(name).replace(/-/g, "_").toUpperCase();
const scaleId = (key) => `s${key}`; // spacing "200" → s200 (Swift/Kotlin identifiers cannot start with a digit)

const hexBody = (hex) => {
  const h = hex.slice(1).toUpperCase();
  return h.length === 6 ? { rgb: h, a: "FF" } : { rgb: h.slice(0, 6), a: h.slice(6) };
};
const swiftRGBA = (hex) => { const { rgb, a } = hexBody(hex); return `0x${rgb}${a}`; };
const kotlinARGB = (hex) => { const { rgb, a } = hexBody(hex); return `0x${a}${rgb}L`; };

const num = (n) => (Number.isInteger(n) ? `${n}` : `${n}`);
const swiftDouble = (n) => (Number.isInteger(n) ? `${n}` : `${n}`);
const ktFloat = (n) => `${n}f`;

const swiftStr = (s) => `"${s.replace(/\\/g, "\\\\").replace(/"/g, '\\"')}"`;
const ktStr = (s) => `"${s.replace(/\\/g, "\\\\").replace(/"/g, '\\"').replace(/\$/g, "\\$")}"`;
const tsStr = (s) => JSON.stringify(s);

