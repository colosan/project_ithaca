// swift-tools-version: 6.0
// Ithaca Apple apps (ADR-0004). Built with SwiftPM so it needs only the Command Line Tools, not Xcode (ADR-0008).
// The Rust core is linked as a static library built by tools/mac/build.sh (core/target/release/libithaca_ffi.a).
import Foundation
import PackageDescription

let repo = URL(fileURLWithPath: #filePath).deletingLastPathComponent().deletingLastPathComponent()
let coreLib = repo.appendingPathComponent("core/target/release").path

let package = Package(
    name: "Ithaca",
    defaultLocalization: "ko",
    platforms: [.macOS(.v14)],
    products: [
        .executable(name: "Ithaca", targets: ["IthacaMac"]),
    ],
    dependencies: [
        // Auto-update (ADR-0008). MIT. Embedded into Ithaca.app by tools/mac/embed-frameworks.sh.
        .package(url: "https://github.com/sparkle-project/Sparkle", from: "2.10.0"),
    ],
    targets: [
        // UniFFI C header + modulemap, generated by tools/mac/build.sh (not checked in).
        .target(
            name: "IthacaCoreFFI",
            path: "Sources/IthacaCoreFFI",
            linkerSettings: [.unsafeFlags(["-L", coreLib]), .linkedLibrary("ithaca_ffi")]
        ),
        // Swift face of the core: generated UniFFI bindings + hand-written conveniences.
        .target(
            name: "IthacaCore",
            dependencies: ["IthacaCoreFFI"],
            path: "Sources/IthacaCore",
            swiftSettings: [.swiftLanguageMode(.v5)]
        ),
        // Tokens, strings, icons generated from design/ (pnpm design:gen).
        .target(
            name: "IthacaDesign",
            path: "Packages/IthacaDesign/Sources/IthacaDesign"
        ),
        .executableTarget(
            name: "IthacaMac",
            dependencies: ["IthacaCore", "IthacaDesign", .product(name: "Sparkle", package: "Sparkle")],
            path: "Sources/IthacaMac",
            // Sparkle.framework lives in Ithaca.app/Contents/Frameworks (tools/mac/embed-frameworks.sh).
            linkerSettings: [.unsafeFlags(["-Xlinker", "-rpath", "-Xlinker", "@executable_path/../Frameworks"])]
        ),
    ]
)
